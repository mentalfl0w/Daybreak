// MARK: - Display info

public struct MacDisplayInfo: Hashable, Sendable, Identifiable {
    public let displayID: DesktopDisplayID
    public let localizedName: String
    public let pixelWidth: Int
    public let pixelHeight: Int
    public let isMain: Bool
    public let currentImageURL: URL?
    public let currentOptions: MacWallpaperOptions

    public init(
        displayID: DesktopDisplayID,
        localizedName: String,
        pixelWidth: Int,
        pixelHeight: Int,
        isMain: Bool,
        currentImageURL: URL?,
        currentOptions: MacWallpaperOptions
    ) {
        self.displayID = displayID
        self.localizedName = localizedName
        self.pixelWidth = pixelWidth
        self.pixelHeight = pixelHeight
        self.isMain = isMain
        self.currentImageURL = currentImageURL
        self.currentOptions = currentOptions
    }

    public var id: DesktopDisplayID { displayID }
}

// MARK: - Write preflight

/// One display as it was observed when the user prepared an explicit write.
///
/// This is a transient preflight observation, not a backup: it is held only
/// while a write confirmation is pending, is used to detect a Space, display or
/// wallpaper change, and is never persisted or offered as a restore point.
public struct MacPreflightDisplayObservation: Hashable, Codable, Sendable, Identifiable {
    public let displayID: DesktopDisplayID
    public let localizedName: String
    public let imageURL: URL?
    public let options: MacWallpaperOptions

    public init(
        displayID: DesktopDisplayID,
        localizedName: String,
        imageURL: URL?,
        options: MacWallpaperOptions
    ) {
        self.displayID = displayID
        self.localizedName = localizedName
        self.imageURL = imageURL
        self.options = options
    }

    public var id: DesktopDisplayID { displayID }
}

/// The accessible desktops observed for one pending write confirmation.
///
/// Public APIs cannot enumerate inactive Spaces, so this is only the desktop
/// currently reachable for each display. It is not a backup of the original
/// wallpaper and Daybreak does not provide a restore flow.
public struct MacPreflightDesktopObservation: Hashable, Codable, Sendable {
    public let capturedAt: Date
    public let screensHaveSeparateSpaces: Bool
    public let displays: [MacPreflightDisplayObservation]

    public init(
        capturedAt: Date,
        screensHaveSeparateSpaces: Bool,
        displays: [MacPreflightDisplayObservation]
    ) {
        self.capturedAt = capturedAt
        self.screensHaveSeparateSpaces = screensHaveSeparateSpaces
        self.displays = displays
    }
}

/// One-use internal token for a write the user explicitly confirmed. It is
/// generated by the confirmation button, never persisted, and invalidated by
/// any Space/wallpaper change.
public struct MacWallpaperWritePreflight: Hashable, Codable, Sendable, Identifiable {
    public let id: UUID
    public let preparedAt: Date
    public let expiresAt: Date
    public let observation: MacPreflightDesktopObservation

    public init(
        id: UUID = UUID(),
        preparedAt: Date,
        expiresAt: Date,
        observation: MacPreflightDesktopObservation
    ) {
        self.id = id
        self.preparedAt = preparedAt
        self.expiresAt = expiresAt
        self.observation = observation
    }
}

public struct MacWallpaperWriteConsent: Sendable, Equatable {
    public let preflightID: UUID

    public init(preflight: MacWallpaperWritePreflight) {
        self.preflightID = preflight.id
    }
}

// MARK: - Reports and errors

public struct MacDesktopApplyReport: Sendable, Equatable {
    public let reconcileReport: DesktopReconcileReport?
    public let blocked: [MacWriteGuardBlock]

    public init(
        reconcileReport: DesktopReconcileReport?,
        blocked: [MacWriteGuardBlock]
    ) {
        self.reconcileReport = reconcileReport
        self.blocked = blocked
    }
}

public enum MacDesktopApplyError: Error, Equatable, Sendable, LocalizedError {
    case notRunning
    case writePreflightRequired
    case preflightExpired
    case preflightMismatch
    case noPendingPreflight
    case unknownDisplay(DesktopDisplayID)
    case persistenceFailed(String)

    public var errorDescription: String? {
        switch self {
        case .notRunning:
            return "Desktop integration has not been started."
        case .writePreflightRequired:
            return "Complete one write confirmation before writing."
        case .preflightExpired:
            return "The write confirmation expired or was invalidated by a desktop change. Confirm again."
        case .preflightMismatch:
            return "The display, wallpaper, or desktop options changed after confirmation."
        case .noPendingPreflight:
            return "No write confirmation has been prepared."
        case .unknownDisplay(let displayID):
            return "Display \(displayID) is not connected."
        case .persistenceFailed(let reason):
            return "Desktop settings could not be saved: \(reason)"
        }
    }
}

// MARK: - Snapshot

public struct MacDesktopSnapshot: Sendable, Equatable {
    public let isRunning: Bool
    public let automationMode: MacDesktopAutomationMode
    public let automaticOverwriteEnabled: Bool
    public let assignments: [DesktopDisplayAssignment]
    public let displays: [MacDisplayInfo]
    /// Every URL Daybreak successfully wrote. This ledger survives launches and
    /// lets the app keep all previously written images protected even when the
    /// inactive Space that still shows one cannot be enumerated.
    public let managedImageURLs: Set<URL>
    /// Last successfully written wallpaper URL per display. Only successful
    /// backend writes update this map; failures leave the previous entry.
    public let appliedWallpaperURLsByDisplay: [DesktopDisplayID: URL]
    /// Connected displays whose last confirmed write has not yet been observed
    /// by a later, trustworthy system read.
    ///
    /// A freshly written wallpaper can lag the public desktop observation.
    /// While a display is listed here, its `currentImageURL` may still describe
    /// the pre-write desktop, so consumers must treat the confirmed entry in
    /// `appliedWallpaperURLsByDisplay` as the image to protect and must not
    /// release that protection based on `currentImageURL`.
    public let displaysAwaitingWriteObservation: Set<DesktopDisplayID>
    public let coordinatorState: DesktopCoordinatorState?
    public let writeAccess: MacWallpaperWriteAccess
    public let guardBlocks: [MacWriteGuardBlock]
    public let manualProtections: [MacManualProtectionRecord]
    public let pendingPreflight: MacWallpaperWritePreflight?
    /// Structured settings problem for app-side localized copy. Technical
    /// diagnostics stay in `MacDesktopSettingsIssue.detail`.
    public let lastIssue: MacDesktopSettingsIssue?

    public init(
        isRunning: Bool,
        automationMode: MacDesktopAutomationMode,
        automaticOverwriteEnabled: Bool = false,
        assignments: [DesktopDisplayAssignment],
        displays: [MacDisplayInfo],
        managedImageURLs: Set<URL> = [],
        appliedWallpaperURLsByDisplay: [DesktopDisplayID: URL] = [:],
        displaysAwaitingWriteObservation: Set<DesktopDisplayID> = [],
        coordinatorState: DesktopCoordinatorState?,
        writeAccess: MacWallpaperWriteAccess,
        guardBlocks: [MacWriteGuardBlock],
        manualProtections: [MacManualProtectionRecord],
        pendingPreflight: MacWallpaperWritePreflight?,
        lastIssue: MacDesktopSettingsIssue?
    ) {
        self.isRunning = isRunning
        self.automationMode = automationMode
        self.automaticOverwriteEnabled = automaticOverwriteEnabled
        self.assignments = assignments
        self.displays = displays
        self.managedImageURLs = managedImageURLs
        self.appliedWallpaperURLsByDisplay = appliedWallpaperURLsByDisplay
        self.displaysAwaitingWriteObservation = displaysAwaitingWriteObservation
        self.coordinatorState = coordinatorState
        self.writeAccess = writeAccess
        self.guardBlocks = guardBlocks
        self.manualProtections = manualProtections
        self.pendingPreflight = pendingPreflight
        self.lastIssue = lastIssue
    }

    /// Technical diagnostic only. User-facing copy is derived from
    /// `lastIssue` by the app; never show this string directly.
    public var lastError: String? {
        guard let lastIssue else { return nil }
        let detail = lastIssue.detail ?? "no detail"
        return "\(lastIssue.kind.rawValue): \(detail)"
    }

    /// Displays whose persisted assignment predates provenance tracking.
    ///
    /// Automatic target updates deliberately preserve these assignments, so
    /// they will not advance with later content until the user explicitly
    /// re-enables automatic sync. The app must surface this instead of
    /// presenting every display as normally synchronized.
    public var legacyAssignmentDisplayIDs: [DesktopDisplayID] {
        assignments
            .filter { $0.source == .unknown }
            .map(\.displayID)
            .sorted()
    }
}

// MARK: - Integration

/// App-facing façade for macOS desktop wallpapers.
///
/// All methods are main-actor isolated. `start()` never writes a wallpaper;
/// it restores an explicitly persisted automatic-sync mode. Writes happen only
/// through `applyOnce` (one explicit user confirmation with a fresh internal
/// preflight) or through automatic mode after the user opted in. Even then
/// `MacOverwritePolicy` refuses an unverified external wallpaper unless the
/// user separately enabled automatic overwrite, and manual protection always
/// wins.
@MainActor
public final class MacDesktopIntegration {
    public private(set) var snapshot: MacDesktopSnapshot
    public var onSnapshotChange: ((MacDesktopSnapshot) -> Void)?

    private static let preflightLifetime: TimeInterval = 15 * 60

    private let store: MacDesktopSettingsStore
    private let system: any MacWallpaperSystem
    private let eventObserver: any MacSystemEventObserving
    private let pointerObserver: any MacPointerDisplayObserving
    private let eventDebounce: Duration
    private let now: @Sendable () -> Date
    private let gate: MacWallpaperWriteGate
    private let audit: MacWriteGuardAudit
    private let manualWriteBroker: MacManualWriteBroker
    private let protectionBox: MacWallpaperProtectionBox
    private let applier: MacWallpaperApplier

    private var coordinator: DesktopCoordinator?
    private var eventObservation: MacSystemEventObservation?
    private var pointerObservation: MacSystemEventObservation?
    private var settings = MacDesktopSettings.default
    private var displays: [MacDisplayInfo] = []
    /// Writes confirmed by the backend but not yet matched by a trustworthy
    /// desktop observation. The in-pass post-write read and one following read
    /// may still lag the system agent, so the entry is released on the third
    /// observation after the write unless the confirmed image appears first.
    private struct PendingWriteObservation {
        let imageURL: URL
        let baselineObservationSequence: UInt64
    }
    private var pendingWriteObservations: [DesktopDisplayID: PendingWriteObservation] = [:]
    /// Monotonic count of desktop observations. It lets a pending write tell
    /// in-pass reads from later, independent reads without wall-clock timing.
    private var displayObservationSequence: UInt64 = 0
    private var pendingEvent: MacSystemEvent?
    /// A pointer crossing is coalesced with a pending system event, but is not
    /// itself a `MacSystemEvent`: it must never invalidate a prepared write
    /// preflight or bump `eventGeneration` like a Space change does.
    private var pendingPointerTrigger = false
    private var debounceTask: Task<Void, Never>?
    private var pendingPreflight: MacWallpaperWritePreflight?
    private var preflightInvalidated = false
    private var eventGeneration: UInt64 = 0
    /// Guards against an older `publish()` that started earlier (and awaited
    /// several actors) overwriting a newer snapshot.
    private var publishGeneration: UInt64 = 0
    private var isRunning = false
    private var coordinatorNeedsRebuild = false
    private var passInProgress = false
    private var passWaiters: [CheckedContinuation<Void, Never>] = []
    private var loadIssue: MacDesktopSettingsIssue?

    public init(
        settingsDirectory: URL? = nil,
        system: any MacWallpaperSystem = AppKitWallpaperSystem(),
        eventObserver: any MacSystemEventObserving = AppKitSystemEventObserver(),
        pointerObserver: any MacPointerDisplayObserving = AppKitPointerDisplayObserver(),
        eventDebounce: Duration = .milliseconds(250),
        wallpaperProtection: (any WallpaperApplicationProtecting)? = nil,
        now: @escaping @Sendable () -> Date = { Date() }
    ) {
        self.system = system
        self.eventObserver = eventObserver
        self.pointerObserver = pointerObserver
        self.eventDebounce = eventDebounce
        self.now = now
        let store = MacDesktopSettingsStore(directory: settingsDirectory, now: now)
        self.store = store
        let gate = MacWallpaperWriteGate()
        self.gate = gate
        let audit = MacWriteGuardAudit()
        self.audit = audit
        let manualWriteBroker = MacManualWriteBroker()
        self.manualWriteBroker = manualWriteBroker
        let protectionBox = MacWallpaperProtectionBox(wallpaperProtection)
        self.protectionBox = protectionBox
        self.applier = MacWallpaperApplier(
            system: system,
            gate: gate,
            store: store,
            audit: audit,
            manualWriteBroker: manualWriteBroker,
            protection: protectionBox,
            now: now
        )
        self.snapshot = MacDesktopSnapshot(
            isRunning: false,
            automationMode: .readOnly,
            automaticOverwriteEnabled: false,
            assignments: [],
            displays: [],
            managedImageURLs: [],
            appliedWallpaperURLsByDisplay: [:],
            coordinatorState: nil,
            writeAccess: .readOnly,
            guardBlocks: [],
            manualProtections: [],
            pendingPreflight: nil,
            lastIssue: nil
        )
    }

    // MARK: Lifecycle

    /// Connects the shared repository after this integration has been created.
    /// Until this is called, every wallpaper write is refused.
    public func setWallpaperProtection(
        _ protection: any WallpaperApplicationProtecting
    ) async {
        await protectionBox.set(protection)
    }

    /// Loads persisted settings and observes system events. Never writes a
    /// wallpaper; an explicitly persisted automatic-sync mode reopens the
    /// write gate for later event-driven reconciliation, while invalid or
    /// unreadable settings stay read-only.
    public func start() async {
        guard !isRunning else { return }
        pendingPreflight = nil
        preflightInvalidated = false
        eventGeneration = 0
        pendingWriteObservations.removeAll()
        manualWriteBroker.end()
        loadIssue = nil
        settings = await store.load()
        loadIssue = await store.currentLoadIssue()
        let legacyAssignmentCount = settings.assignments
            .filter { $0.source == .unknown }
            .count
        if legacyAssignmentCount > 0 {
            // These assignments predate provenance. Automatic target updates
            // retain them, so they will not advance with new content. Make the
            // limitation observable instead of silently reporting every
            // display as normally synchronized.
            MacIntegrationLog.logger.notice(
                "Desktop settings contain legacy assignments count=\(legacyAssignmentCount, privacy: .public); automatic target updates will not replace them until the user re-enables automatic sync"
            )
        }
        rebuildCoordinator()
        coordinatorNeedsRebuild = false

        if settings.automationMode == .automatic {
            await gate.grant()
        } else {
            await gate.revoke()
        }

        isRunning = true
        eventObservation = eventObserver.observe { [weak self] event in
            Task { @MainActor [weak self] in
                self?.receive(event)
            }
        }
        pointerObservation = pointerObserver.observeDisplayChanges { [weak self] change in
            Task { @MainActor [weak self] in
                self?.receive(pointerChange: change)
            }
        }
        // Read after subscribing. A display connected between launch and
        // observer installation must not be missed; this is one event-driven
        // read, not periodic polling.
        displays = await refreshDisplayObservation()
        await publish()
        MacIntegrationLog.logger.notice(
            "Desktop integration started mode=\(self.settings.automationMode.rawValue, privacy: .public) displays=\(self.displays.count, privacy: .public) issue=\(self.loadIssue?.kind.rawValue ?? "none", privacy: .public)"
        )
    }

    public func stop() {
        guard isRunning else { return }
        isRunning = false
        eventObservation?.cancel()
        eventObservation = nil
        pointerObservation?.cancel()
        pointerObservation = nil
        debounceTask?.cancel()
        debounceTask = nil
        pendingEvent = nil
        pendingPointerTrigger = false
        pendingWriteObservations.removeAll()
        coordinator = nil
        manualWriteBroker.end()
        MacIntegrationLog.logger.notice("Desktop integration stopped")
        // Fail closed as soon as the actor can run. The guards below keep a
        // stop() that races a later start() from closing the new session's
        // gate or publishing a stopped snapshot.
        Task { @MainActor [weak self] in
            guard let self, !self.isRunning else { return }
            await self.gate.revoke()
        }
        Task { @MainActor [weak self] in
            guard let self, !self.isRunning else { return }
            await self.publish()
        }
    }

    /// Read-only topology refresh. Never invokes the coordinator.
    public func refresh() async {
        guard isRunning else { return }
        displays = await refreshDisplayObservation()
        await publish()
        MacIntegrationLog.logger.debug(
            "Desktop topology refreshed displays=\(self.displays.count, privacy: .public)"
        )
    }

    // MARK: Explicit manual apply

    public func prepareWallpaperWrite() async throws -> MacWallpaperWritePreflight {
        guard isRunning else { throw MacDesktopApplyError.notRunning }
        // A new confirmation supersedes any previous token. If a manual pass
        // is still running, its write-side scope is invalidated so it fails
        // closed instead of continuing with the replaced observation.
        invalidatePreflight()
        let generation = eventGeneration
        let observation = await captureAccessibleDesktopObservation()
        guard generation == eventGeneration else {
            await publish()
            throw MacDesktopApplyError.preflightExpired
        }
        let preparedAt = now()
        let preflight = MacWallpaperWritePreflight(
            id: UUID(),
            preparedAt: preparedAt,
            expiresAt: preparedAt.addingTimeInterval(Self.preflightLifetime),
            observation: observation
        )
        pendingPreflight = preflight
        preflightInvalidated = false
        await publish()
        MacIntegrationLog.logger.notice(
            "Desktop preflight prepared displays=\(observation.displays.count, privacy: .public)"
        )
        return preflight
    }

    /// Applies targets to the currently accessible desktops after an explicit
    /// manual request. The preflight must still match the live display URLs and
    /// options immediately before the pass, after waiting for any in-flight
    /// pass, and after opening the write gate. A write-side broker keeps the
    /// same contract enforced at the moment of each backend write.
    public func applyOnce(
        _ targets: [DesktopDisplayID: DesktopWallpaper],
        consent: MacWallpaperWriteConsent
    ) async throws -> MacDesktopApplyReport {
        guard isRunning else { throw MacDesktopApplyError.notRunning }
        let preflight = try validatedPreflight(for: consent)
        guard coordinator != nil else { throw MacDesktopApplyError.notRunning }
        if targets.isEmpty {
            return MacDesktopApplyReport(
                reconcileReport: nil,
                blocked: await audit.snapshot()
            )
        }

        // Initial verification before persisting intent or changing protection.
        _ = try await verifyManualTargets(targets, preflight: preflight)

        settings = try await store.mergeAssignments(targets, source: .manual)
        try await ensurePreflightStillValid(preflight)
        // Manual protection is intentionally NOT removed before the write. The
        // one-display confirmation authorizes this pass through the manual
        // write broker, and the persisted protection survives any failure,
        // cancellation, or Space switch between here and the actual write.
        // Clear only the confirmed targets: a scoped manual apply must not
        // erase another display's pause reason.
        for displayID in targets.keys.sorted() {
            await audit.clear(displayID: displayID)
        }
        displays = await refreshDisplayObservation()
        try await ensurePreflightStillValid(preflight)
        await publish()

        await beginPass()
        defer {
            manualWriteBroker.end()
            endPass()
        }

        // Re-verify after waiting for any pass that was already running.
        // Space switches and wallpaper changes during the wait must invalidate
        // the preflight rather than allowing the queued write.
        try await ensurePreflightStillValid(preflight)
        _ = try await verifyManualTargets(targets, preflight: preflight)
        try await ensurePreflightStillValid(preflight)

        prepareCoordinatorForNextPass()
        guard let coordinator else { throw MacDesktopApplyError.notRunning }

        await gate.grant()
        defer {
            if settings.automationMode != .automatic {
                Task { await self.gate.revoke() }
            }
        }

        // `gate.grant()` is an actor hop. An event or wallpaper change may have
        // landed while waiting, so verify the live state again and only then
        // publish the write-side scope.
        try await ensurePreflightStillValid(preflight)
        let verified = try await verifyManualTargets(targets, preflight: preflight)
        try await ensurePreflightStillValid(preflight)
        manualWriteBroker.begin(
            MacManualWriteScope(
                preflightID: preflight.id,
                expiresAt: preflight.expiresAt,
                wallpaperByDisplay: targets,
                verifiedByDisplay: verified,
                restrictsNonTargets: settings.automationMode != .automatic,
                overridesManualProtection: true
            )
        )

        // A manual apply is always a per-display request, including while
        // automatic sync is on. Retained targets for other displays must not
        // be reconciled by this explicit action: the confirmation named one
        // display, and a write elsewhere would exceed it.
        let scope = Set(targets.keys)
        let report = await coordinator.assign(targets, reconcilingOnly: scope)
        let invalidatedDuringPass = manualWriteBroker.isInvalidated
        let blockedTargets = manualWriteBroker.blocked.intersection(Set(targets.keys))
        noteAppliedWrites(report, targets: targets)
        // Publish the desktop actually left by this pass. A successful write
        // must never be projected through the pre-write observation; a lagging
        // system read is handled by `displaysAwaitingWriteObservation`.
        displays = await refreshDisplayObservation()

        // Only a synchronized display is a confirmed success. Remove its
        // persisted protection after the write; a failed, skipped, or
        // invalidated target keeps the user's protection intact.
        let synchronizedTargets = Set(
            report.outcomes
                .filter { targets.keys.contains($0.displayID) && $0.status == .synchronized }
                .map(\.displayID)
        )
        if !synchronizedTargets.isEmpty {
            if let updated = try? await store.removeManualProtections(for: synchronizedTargets) {
                settings = updated
            }
        }

        if settings.automationMode != .automatic {
            await gate.revoke()
        }
        await publish()
        MacIntegrationLog.logger.notice(
            "Manual apply finished displays=\(targets.count, privacy: .public) synchronized=\(synchronizedTargets.count, privacy: .public) blocked=\(blockedTargets.count, privacy: .public) invalidated=\(invalidatedDuringPass ? "yes" : "no", privacy: .public)"
        )

        if invalidatedDuringPass {
            throw MacDesktopApplyError.preflightExpired
        }
        if !blockedTargets.isEmpty {
            throw MacDesktopApplyError.preflightMismatch
        }
        return MacDesktopApplyReport(
            reconcileReport: report,
            blocked: await audit.snapshot()
        )
    }

    /// Resolves a guard block after the user explicitly confirms replacing the
    /// exact wallpaper they saw. The live observed URL is re-read so a stale
    /// request cannot overwrite a newer wallpaper.
    public func confirmOverwrite(
        _ request: MacOverwriteConfirmationRequest
    ) async throws -> MacDesktopApplyReport {
        guard isRunning, coordinator != nil else {
            throw MacDesktopApplyError.notRunning
        }
        if settings.automationMode != .automatic {
            // The confirmation button may be pressed from the menu bar after a
            // relaunch, when no manual-apply preflight exists. Generate the
            // internal safety token now and validate it against the live
            // desktop below; the user already saw the exact display/image.
            if pendingPreflight == nil || now() >= (pendingPreflight?.expiresAt ?? .distantPast) {
                _ = try await prepareWallpaperWrite()
            }
            guard let pending = pendingPreflight else {
                throw MacDesktopApplyError.writePreflightRequired
            }
            guard now() < pending.expiresAt else {
                throw MacDesktopApplyError.preflightExpired
            }
        }
        guard let assignment = settings.assignments.first(where: {
            $0.displayID == request.displayID
        }) else {
            throw MacDesktopApplyError.unknownDisplay(request.displayID)
        }
        guard assignment.wallpaper == request.desiredWallpaper else {
            throw MacDesktopApplyError.preflightMismatch
        }
        let screens = await system.screens()
        guard let current = screens.first(where: {
            $0.displayID == request.displayID
        }) else {
            throw MacDesktopApplyError.unknownDisplay(request.displayID)
        }
        // Nil never matches nil: an unreadable current wallpaper cannot be
        // approved by a stale request.
        guard let observedURL = request.observedImageURL,
              let currentURL = current.imageURL,
              currentURL == observedURL else {
            throw MacDesktopApplyError.preflightMismatch
        }

        // Do not delete a persisted manual protection before the write. The
        // one-display confirmation authorizes this exact pass through the
        // broker; the protection is removed only after a synchronized result.
        await store.addApproval(
            displayID: request.displayID,
            observedImageURL: observedURL,
            target: request.desiredWallpaper
        )
        await audit.clear(displayID: request.displayID)
        displays = await refreshDisplayObservation()

        let generation = eventGeneration
        await beginPass()
        defer { endPass() }
        guard isRunning else { throw MacDesktopApplyError.notRunning }

        // A Space switch can leave the same URL visible. Any event between the
        // request and the pass invalidates the one-display confirmation.
        guard generation == eventGeneration else {
            throw MacDesktopApplyError.preflightMismatch
        }
        if settings.automationMode != .automatic {
            guard let pending = pendingPreflight else {
                throw MacDesktopApplyError.writePreflightRequired
            }
            try await ensurePreflightStillValid(pending)
        }
        let recheckedScreens = await system.screens()
        guard let rechecked = recheckedScreens.first(where: {
            $0.displayID == request.displayID
        }),
        rechecked.imageURL == observedURL else {
            throw MacDesktopApplyError.preflightMismatch
        }

        prepareCoordinatorForNextPass()
        guard let coordinator else { throw MacDesktopApplyError.notRunning }
        // A guard confirmation is an explicit, one-display write. Open the gate
        // for it even in read-only mode, where the guard could only have been
        // created by a manual-apply pass.
        await gate.grant()
        // The grant is an actor hop. An event during that hop may have
        // invalidated the observation before the broker scope existed; do not
        // let a freshly-begun scope hide it.
        guard generation == eventGeneration else {
            if settings.automationMode != .automatic {
                await gate.revoke()
            }
            throw MacDesktopApplyError.preflightMismatch
        }
        let expiresAt = settings.automationMode == .automatic
            ? now().addingTimeInterval(60)
            : (pendingPreflight?.expiresAt ?? now().addingTimeInterval(60))
        manualWriteBroker.begin(
            MacManualWriteScope(
                preflightID: pendingPreflight?.id ?? UUID(),
                expiresAt: expiresAt,
                wallpaperByDisplay: [request.displayID: request.desiredWallpaper],
                verifiedByDisplay: [
                    request.displayID: MacVerifiedDisplayObservation(
                        imageURL: observedURL,
                        options: rechecked.options
                    )
                ],
                restrictsNonTargets: settings.automationMode != .automatic,
                overridesManualProtection: true
            )
        )
        defer { manualWriteBroker.end() }

        // A guard confirmation is exactly one display, in every mode.
        let report = await coordinator.assign(
            [request.displayID: request.desiredWallpaper],
            reconcilingOnly: [request.displayID]
        )
        noteAppliedWrites(
            report,
            targets: [request.displayID: request.desiredWallpaper]
        )
        // Do not publish the observation captured before this write.
        displays = await refreshDisplayObservation()
        let synchronized = report.outcomes.contains {
            $0.displayID == request.displayID && $0.status == .synchronized
        }
        if synchronized, request.reason == .manualProtection {
            if let updated = try? await store.removeManualProtection(
                displayID: request.displayID
            ) {
                settings = updated
            }
        }
        if settings.automationMode != .automatic {
            await gate.revoke()
        }
        await publish()
        MacIntegrationLog.logger.notice(
            "Guard confirmation display=\(request.displayID.rawValue, privacy: .private) reason=\(request.reason.rawValue, privacy: .public) synchronized=\(synchronized ? "yes" : "no", privacy: .public)"
        )
        return MacDesktopApplyReport(
            reconcileReport: report,
            blocked: await audit.snapshot()
        )
    }

