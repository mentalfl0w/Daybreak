    // MARK: Automation

    /// Enables or disables automatic mode. Enabling validates the preflight and
    /// opens the write gate for future events, but performs no coordinator pass
    /// and records no overwrite approval.
    public func setAutomationEnabled(
        _ enabled: Bool,
        consent: MacWallpaperWriteConsent?
    ) async throws {
        guard isRunning else { throw MacDesktopApplyError.notRunning }
        if enabled {
            if settings.automationMode != .automatic {
                guard let consent else {
                    throw MacDesktopApplyError.writePreflightRequired
                }
                _ = try validatedPreflight(for: consent)
            }
            settings = try await store.setAutomationMode(.automatic)
            await gate.grant()
        } else {
            // Fail closed: close the write path before persistence. If the
            // save fails, the current session stays read-only in memory and
            // the error is observable instead of leaving the app writable
            // while the UI reports "disabled".
            await gate.revoke()
            invalidatePreflight()
            debounceTask?.cancel()
            debounceTask = nil
            pendingEvent = nil
            pendingPointerTrigger = false
            do {
                settings = try await store.setAutomationMode(.readOnly)
            } catch {
                settings = await store.forceAutomationModeReadOnlyInMemory()
                settings.automationMode = .readOnly
                await publish()
                throw error
            }
        }
        await publish()
    }

    /// Persists the independent consent to replace unverified wallpapers
    /// during event-driven reconciliation. This never grants the write gate;
    /// auto sync must also be active, and manual protection still wins.
    public func setAutomaticOverwriteEnabled(_ enabled: Bool) async throws {
        guard isRunning else { throw MacDesktopApplyError.notRunning }
        settings = try await store.setAutomaticOverwriteEnabled(enabled)
        if enabled {
            // Old guard blocks described the previous, confirm-per-display
            // policy. Actual manual protections are projected again on publish.
            await audit.clearAll()
        }
        refreshCoordinatorAfterAssignmentChange()
        await publish()
    }

    /// Explicit reconciliation request. Only forwarded in automatic mode and
    /// still subject to the overwrite guard.
    public func requestReconciliation() async {
        guard isRunning,
              settings.automationMode == .automatic,
              coordinator != nil
        else {
            return
        }
        await beginPass()
        defer { endPass() }
        guard isRunning, settings.automationMode == .automatic else { return }
        prepareCoordinatorForNextPass()
        guard let coordinator else { return }
        let report = await coordinator.handle(.manualRequest)
        noteAppliedWrites(report, targets: settings.assignmentMap)
        // The pass may have left the accessible desktop in a new state.
        displays = await refreshDisplayObservation()
        await publish()
    }

    // MARK: Manual protection

    public func protectCurrentWallpaper(
        for displayID: DesktopDisplayID
    ) async throws {
        guard isRunning else { throw MacDesktopApplyError.notRunning }
        let screens = await system.screens()
        guard let screen = screens.first(where: {
            $0.displayID == displayID
        }) else {
            throw MacDesktopApplyError.unknownDisplay(displayID)
        }
        settings = try await store.protect(
            displayID: displayID,
            imageURL: screen.imageURL,
            options: screen.options,
            at: now()
        )
        await audit.clear(displayID: displayID)
        await publish()
    }

    /// Clears protection. In automatic mode this is an explicit user request to
    /// resume automation, so the currently observed wallpaper and target are
    /// recorded as a one-shot approval before one reconciliation pass. The
    /// persisted protection is removed only after that pass synchronizes the
    /// display; a failure or Space switch keeps it intact.
    public func clearManualProtection(
        for displayID: DesktopDisplayID
    ) async throws -> MacDesktopApplyReport? {
        guard isRunning else { throw MacDesktopApplyError.notRunning }

        guard settings.automationMode == .automatic,
              coordinator != nil,
              let target = settings.assignments.first(where: {
                  $0.displayID == displayID
              })?.wallpaper
        else {
            settings = try await store.removeManualProtection(displayID: displayID)
            await audit.clear(displayID: displayID)
            await publish()
            return nil
        }

        let screens = await system.screens()
        guard let screen = screens.first(where: {
            $0.displayID == displayID
        }), let observedURL = screen.imageURL else {
            // No verifiable write is possible. Releasing protection is still
            // the user's explicit choice, but nothing is written.
            settings = try await store.removeManualProtection(displayID: displayID)
            await audit.clear(displayID: displayID)
            await publish()
            return nil
        }
        await store.addApproval(
            displayID: displayID,
            observedImageURL: observedURL,
            target: target
        )
        let generation = eventGeneration
        await beginPass()
        defer { endPass() }
        guard isRunning,
              settings.automationMode == .automatic,
              generation == eventGeneration
        else {
            return nil
        }
        prepareCoordinatorForNextPass()
        guard let coordinator else { return nil }
        let rechecked = await system.screens()
        guard let current = rechecked.first(where: {
            $0.displayID == displayID
        }), current.imageURL == observedURL else {
            return nil
        }
        await gate.grant()
        // Re-check after the actor hop: disabling automation or a desktop
        // event while the gate was reopening must cancel this pass instead of
        // leaving a new, unscoped authorization behind.
        guard isRunning,
              settings.automationMode == .automatic,
              generation == eventGeneration
        else {
            if settings.automationMode != .automatic {
                await gate.revoke()
            }
            return nil
        }
        manualWriteBroker.begin(
            MacManualWriteScope(
                preflightID: UUID(),
                expiresAt: now().addingTimeInterval(60),
                wallpaperByDisplay: [displayID: target],
                verifiedByDisplay: [
                    displayID: MacVerifiedDisplayObservation(
                        imageURL: observedURL,
                        options: current.options
                    )
                ],
                restrictsNonTargets: false,
                overridesManualProtection: true
            )
        )
        defer { manualWriteBroker.end() }
        let report = await coordinator.assign(target, to: displayID)
        noteAppliedWrites(report, targets: [displayID: target])
        displays = await refreshDisplayObservation()
        let synchronized = report.outcomes.contains {
            $0.displayID == displayID && $0.status == .synchronized
        }
        if synchronized {
            if let updated = try? await store.removeManualProtection(
                displayID: displayID
            ) {
                settings = updated
            }
        }
        await publish()
        MacIntegrationLog.logger.notice(
            "Manual protection release display=\(displayID.rawValue, privacy: .private) synchronized=\(synchronized ? "yes" : "no", privacy: .public)"
        )
        return MacDesktopApplyReport(
            reconcileReport: report,
            blocked: await audit.snapshot()
        )
    }

    // MARK: Event handling

    private func receive(_ event: MacSystemEvent) {
        guard isRunning else { return }
        eventGeneration &+= 1
        MacIntegrationLog.logger.debug(
            "Desktop event=\(Self.eventName(event), privacy: .public) mode=\(self.settings.automationMode.rawValue, privacy: .public)"
        )
        // Any observed desktop change makes the captured observation stale:
        // the user may now be looking at a different Space/wallpaper, and
        // public APIs cannot prove that an unchanged URL/options pair belongs
        // to the same desktop. A fresh preflight and confirmation are required
        // before the next write. This is a safety boundary even when it
        // repeats a prompt.
        invalidatePreflight()
        guard settings.automationMode == .automatic else {
            debounceTask?.cancel()
            debounceTask = nil
            pendingPointerTrigger = false
            debounceTask = Task { [weak self] in
                await self?.refresh()
            }
            return
        }

        pendingEvent = Self.merged(pendingEvent, event)
        scheduleDebouncedFlush()
    }

    /// A pointer crossing is an additional opportunity to reconcile the
    /// currently accessible desktops, not a Space or display-topology change.
    /// It deliberately does not call `receive(_:)`: no event generation bump
    /// and no preflight invalidation. The pass is still filtered by automatic
    /// mode, the independent overwrite consent and manual protection.
    private func receive(pointerChange: MacPointerDisplayChange) {
        guard isRunning,
              settings.automationMode == .automatic,
              coordinator != nil,
              pointerChange.previousDisplayID != pointerChange.displayID
        else {
            return
        }
        MacIntegrationLog.logger.debug(
            "Pointer entered another display mode=automatic"
        )
        pendingPointerTrigger = true
        scheduleDebouncedFlush()
    }

    private func scheduleDebouncedFlush() {
        debounceTask?.cancel()
        debounceTask = Task { [weak self] in
            guard let self else { return }
            do {
                try await Task.sleep(for: self.eventDebounce)
            } catch {
                return
            }
            await self.flushPendingEvent()
        }
    }

    private func flushPendingEvent() async {
        guard isRunning,
              settings.automationMode == .automatic,
              coordinator != nil
        else {
            pendingEvent = nil
            pendingPointerTrigger = false
            return
        }
        guard pendingEvent != nil || pendingPointerTrigger else { return }
        let event = pendingEvent
        let pointerTriggered = pendingPointerTrigger
        pendingEvent = nil
        pendingPointerTrigger = false
        await beginPass()
        defer { endPass() }
        guard isRunning, settings.automationMode == .automatic else { return }
        prepareCoordinatorForNextPass()
        guard let coordinator else { return }
        // A pending system event is broader and must keep its semantics (for
        // example, a Space change revokes one-pass adoptions). A pointer-only
        // trigger is a reconciliation request and never claims a Space change.
        let trigger = event.map(Self.desktopEvent(for:)) ?? .manualRequest
        let report = await coordinator.handle(trigger)
        noteAppliedWrites(report, targets: settings.assignmentMap)
        // The pass may have observed a different accessible Space or display
        // set. Refresh the read-only projection so published guard blocks
        // describe the live desktop instead of the snapshot from before.
        displays = await refreshDisplayObservation()
        await publish()
        if pointerTriggered, event == nil {
            MacIntegrationLog.logger.debug(
                "Pointer reconciliation finished displays=\(self.displays.count, privacy: .public)"
            )
        }
    }

    // MARK: Coordinator

    private func rebuildCoordinator() {
        var initialAssignments: [DesktopDisplayID: DesktopWallpaper] = [:]
        for (displayID, wallpaper) in settings.assignmentMap {
            initialAssignments[displayID] = wallpaper
        }
        // Automatic overwrite is a separate, explicit consent. Without it the
        // coordinator keeps protecting unmanaged wallpapers; with it the
        // applier still enforces per-display manual protection.
        let selectionPolicy: DesktopManualSelectionPolicy =
            settings.automaticOverwriteEnabled ? .replaceManualSelections : .protectManualSelections
        coordinator = DesktopCoordinator(
            backend: applier,
            configuration: DesktopCoordinatorConfiguration(
                manualSelectionPolicy: selectionPolicy,
                retryPolicy: .default
            ),
            initialAssignments: initialAssignments,
            managedImageURLs: settings.managedImageURLs,
            retryScheduler: TaskDesktopRetryScheduler(),
            now: now
        )
    }

    private func prepareCoordinatorForNextPass() {
        guard coordinatorNeedsRebuild else { return }
        rebuildCoordinator()
        coordinatorNeedsRebuild = false
    }

    /// Desired-intent changes never write. If no pass is running, replace the
    /// coordinator now so stale retries are dropped and `state()` reflects the
    /// new targets; otherwise defer the replacement to the next pass so a
    /// running pass cannot be disturbed mid-flight.
    private func refreshCoordinatorAfterAssignmentChange() {
        if passInProgress {
            coordinatorNeedsRebuild = true
        } else {
            rebuildCoordinator()
            coordinatorNeedsRebuild = false
        }
    }

    private func beginPass() async {
        while passInProgress {
            await withCheckedContinuation { continuation in
                passWaiters.append(continuation)
            }
        }
        passInProgress = true
    }

    private func endPass() {
        passInProgress = false
        let waiters = passWaiters
        passWaiters.removeAll()
        for waiter in waiters {
            waiter.resume()
        }
    }

    // MARK: Write observation and publish

    private func captureAccessibleDesktopObservation() async -> MacPreflightDesktopObservation {
        let screens = await system.screens()
        let separateSpaces = await system.screensHaveSeparateSpaces()
        let observations = screens
            .sorted { $0.displayID < $1.displayID }
            .map { screen in
                MacPreflightDisplayObservation(
                    displayID: screen.displayID,
                    localizedName: screen.localizedName,
                    imageURL: screen.imageURL,
                    options: screen.options
                )
            }
        return MacPreflightDesktopObservation(
            capturedAt: now(),
            screensHaveSeparateSpaces: separateSpaces,
            displays: observations
        )
    }

    private func readDisplayInfos() async -> [MacDisplayInfo] {
        let infos = await system.screens()
            .sorted { $0.displayID < $1.displayID }
            .map {
                MacDisplayInfo(
                    displayID: $0.displayID,
                    localizedName: $0.localizedName,
                    pixelWidth: $0.pixelWidth,
                    pixelHeight: $0.pixelHeight,
                    isMain: $0.isMain,
                    currentImageURL: $0.imageURL,
                    currentOptions: $0.options
                )
            }
        if Set(infos.map(\.displayID)).count != infos.count {
            // Two screens resolved to the same public identity. Keep both
            // observations; the app must not silently pretend only one display
            // is connected. The warning carries no names or paths.
            MacIntegrationLog.logger.warning(
                "Duplicate desktop display identity observed count=\(infos.count, privacy: .public)"
            )
        }
        return infos
    }

    /// Replaces the published display observation and resolves pending
    /// post-write observations against it.
    ///
    /// Every observable desktop read goes through this method so a write's
    /// confirmed URL is never discarded merely because the system agent has not
    /// caught up yet. A read is only trustworthy for a just-written display
    /// once it reports the confirmed image, or once three independent
    /// observations after the write agree on a different image.
    @discardableResult
    private func refreshDisplayObservation() async -> [MacDisplayInfo] {
        displays = await readDisplayInfos()
        displayObservationSequence &+= 1
        reconcilePendingWriteObservations()
        return displays
    }

    private func reconcilePendingWriteObservations() {
        guard !pendingWriteObservations.isEmpty else { return }
        var resolved: Set<DesktopDisplayID> = []
        for (displayID, pending) in pendingWriteObservations {
            guard let live = displays.first(where: {
                $0.displayID == displayID
            }) else {
                // No accessible desktop: nothing is protected for this
                // display right now. A reconnect performs its own observation.
                resolved.insert(displayID)
                continue
            }
            if live.currentImageURL == pending.imageURL {
                resolved.insert(displayID)
                continue
            }
            // The in-pass read and the first downstream read can lag the
            // system agent. Only a third observation after the write is
            // authoritative that the live desktop really is different.
            if displayObservationSequence
                >= pending.baselineObservationSequence &+ 3 {
                resolved.insert(displayID)
            }
        }
        for displayID in resolved {
            pendingWriteObservations[displayID] = nil
        }
    }

    /// Records displays a reconciliation wrote in this pass. Their confirmed
    /// URLs stay protected until a later observation can prove the live
    /// desktop, so `publish` must not present them as authoritative.
    private func noteAppliedWrites(
        _ report: DesktopReconcileReport,
        targets: [DesktopDisplayID: DesktopWallpaper]
    ) {
        for outcome in report.outcomes where outcome.action == .applied {
            guard let wallpaper = targets[outcome.displayID]
                ?? settings.assignmentMap[outcome.displayID] else {
                continue
            }
            pendingWriteObservations[outcome.displayID] = PendingWriteObservation(
                imageURL: wallpaper.imageURL,
                baselineObservationSequence: displayObservationSequence
            )
        }
    }

    /// Drops a prepared preflight and records why. Used when the accessible
    /// desktop changed (Space/screen/wake/login) or when the live wallpaper
    /// state no longer matches the observation. The user must prepare and
    /// confirm a new preflight.
    private func invalidatePreflight() {
        manualWriteBroker.invalidate()
        guard pendingPreflight != nil else { return }
        pendingPreflight = nil
        preflightInvalidated = true
        MacIntegrationLog.logger.notice(
            "Desktop preflight invalidated by a desktop change"
        )
    }

    /// Invalidate and publish before throwing so the app observes that a new
    /// preflight is required instead of seeing a stale pending observation.
    private func invalidatePreflightAndPublish() async {
        invalidatePreflight()
        await publish()
    }

    private func ensurePreflightStillValid(
        _ preflight: MacWallpaperWritePreflight
    ) async throws {
        guard isRunning else { throw MacDesktopApplyError.notRunning }
        if preflightInvalidated {
            await invalidatePreflightAndPublish()
            throw MacDesktopApplyError.preflightExpired
        }
        guard pendingPreflight?.id == preflight.id else {
            throw MacDesktopApplyError.preflightExpired
        }
    }

    /// Re-reads the live screens and requires every manual target to still
    /// match the preflight observation. A missing display, changed options, or
    /// a changed image URL (including a URL that became unreadable, or an
    /// unreadable wallpaper that became readable) invalidates the preflight
    /// and throws before any approval or write path can proceed.
    ///
    /// When both the observation and the live value report no image URL, the
    /// public APIs cannot prove the same wallpaper. The explicit confirmation,
    /// unchanged options, display presence and synchronous event invalidation
    /// are the authorization boundary. This intentionally does not block a
    /// user-initiated wallpaper change merely because the original system
    /// wallpaper is unreadable, dynamic, or unrecoverable.
    private func verifyManualTargets(
        _ targets: [DesktopDisplayID: DesktopWallpaper],
        preflight: MacWallpaperWritePreflight
    ) async throws -> [DesktopDisplayID: MacVerifiedDisplayObservation] {
        let screens = await system.screens()
        try await ensurePreflightStillValid(preflight)

        var verified: [DesktopDisplayID: MacVerifiedDisplayObservation] = [:]
        for displayID in targets.keys.sorted() {
            guard let current = screens.first(where: {
                $0.displayID == displayID
            }) else {
                await invalidatePreflightAndPublish()
                throw MacDesktopApplyError.unknownDisplay(displayID)
            }
            guard let observation = preflight.observation.displays.first(where: {
                $0.displayID == displayID
            }),
            observation.imageURL == current.imageURL,
            observation.options == current.options else {
                await invalidatePreflightAndPublish()
                throw MacDesktopApplyError.preflightMismatch
            }
            verified[displayID] = MacVerifiedDisplayObservation(
                imageURL: current.imageURL,
                options: current.options
            )
        }

        try await ensurePreflightStillValid(preflight)
        return verified
    }

    private func validatedPreflight(
        for consent: MacWallpaperWriteConsent
    ) throws -> MacWallpaperWritePreflight {
        guard let pending = pendingPreflight else {
            if preflightInvalidated {
                throw MacDesktopApplyError.preflightExpired
            }
            throw MacDesktopApplyError.noPendingPreflight
        }
        guard !preflightInvalidated else {
            throw MacDesktopApplyError.preflightExpired
        }
        guard pending.id == consent.preflightID else {
            throw MacDesktopApplyError.preflightMismatch
        }
        guard now() < pending.expiresAt else {
            throw MacDesktopApplyError.preflightExpired
        }
        return pending
    }

    private func publish() async {
        publishGeneration &+= 1
        let generation = publishGeneration
        var coordinatorState: DesktopCoordinatorState?
        if let coordinator {
            coordinatorState = await coordinator.state()
        }
        let access = await gate.access
        let auditBlocks = await audit.snapshot()
        let persistenceIssue = await store.currentPersistenceIssue()
        // The applier records per-display applied URLs directly in the store
        // after a successful backend write. Read that copy so `publish` does not
        // serve a stale `settings` loaded at launch.
        let storedSettings = await store.snapshot()
        let appliedURLsByDisplay = storedSettings.appliedWallpaperURLsByDisplay
        let managedURLs = storedSettings.managedImageURLs

        // Unify guard refusals, integration-level protection and the
        // coordinator's own external-change protection into one observable
        // list. Precedence: explicit protection, then the applier's latest
        // refusal, then a coordinator-detected change.
        //
        // A guard is an actionable confirmation for exactly one observed
        // wallpaper. Never publish an entry the confirmation flow would reject:
        // an entry for a disconnected display (unknownDisplay) or for a
        // wallpaper that is no longer visible (preflightMismatch) would keep
        // asking the user to confirm the same display forever.
        let liveDisplays = Dictionary(
            displays.map { ($0.displayID, $0) },
            uniquingKeysWith: { _, latest in latest }
        )
        var blocksByDisplay: [DesktopDisplayID: MacWriteGuardBlock] = [:]
        for block in auditBlocks {
            guard let live = liveDisplays[block.displayID] else { continue }
            let isCurrent: Bool
            switch block.reason {
            case .unreadableCurrentWallpaper:
                isCurrent = live.currentImageURL == nil
            case .manualProtection:
                // Protection is enforceable for a connected display even when
                // the visible wallpaper cannot be read. Hiding the pause
                // because the live URL is nil would make automation look idle
                // while it is actually refusing to write.
                isCurrent = true
            case .unverifiedExternalWallpaper:
                isCurrent = block.observedImageURL != nil
                    && live.currentImageURL == block.observedImageURL
            }
            guard isCurrent else { continue }
            blocksByDisplay[block.displayID] = block
        }
        for protection in settings.manualProtections {
            guard let desired = settings.assignments.first(where: {
                $0.displayID == protection.displayID
            })?.wallpaper else {
                continue
            }
            // Protection is persisted and resumes when the display returns, but
            // a disconnected display cannot be confirmed right now.
            guard let live = liveDisplays[protection.displayID] else { continue }
            blocksByDisplay[protection.displayID] = MacWriteGuardBlock(
                displayID: protection.displayID,
                observedImageURL: live.currentImageURL,
                desiredWallpaper: desired,
                reason: .manualProtection,
                detectedAt: protection.protectedAt
            )
        }
        if let coordinatorState {
            for display in coordinatorState.displays {
                guard let protection = display.manualProtection,
                      blocksByDisplay[display.displayID] == nil else {
                    continue
                }
                guard let live = liveDisplays[display.displayID] else { continue }
                guard let desired = display.desiredWallpaper
                    ?? settings.assignmentMap[display.displayID] else {
                    continue
                }
                let observed = live.currentImageURL
                let reason: MacOverwriteBlockReason
                switch protection.origin {
                case .explicitlyRequested:
                    reason = .manualProtection
                case .detectedExternalChange:
                    // An unreadable current wallpaper has no confirmable
                    // image; report the unreadable observation instead of a
                    // stale URL the confirmation flow would reject.
                    reason = observed == nil
                        ? .unreadableCurrentWallpaper
                        : .unverifiedExternalWallpaper
                }
                blocksByDisplay[display.displayID] = MacWriteGuardBlock(
                    displayID: display.displayID,
                    observedImageURL: observed,
                    desiredWallpaper: desired,
                    reason: reason,
                    detectedAt: protection.detectedAt
                )
            }
        }

        let next = MacDesktopSnapshot(
            isRunning: isRunning,
            automationMode: settings.automationMode,
            automaticOverwriteEnabled: settings.automaticOverwriteEnabled,
            assignments: settings.assignments.sorted { $0.displayID < $1.displayID },
            displays: displays,
            managedImageURLs: managedURLs,
            appliedWallpaperURLsByDisplay: appliedURLsByDisplay,
            displaysAwaitingWriteObservation: Set(
                pendingWriteObservations.keys.filter { displayID in
                    displays.contains { $0.displayID == displayID }
                }
            ),
            coordinatorState: coordinatorState,
            writeAccess: access,
            guardBlocks: blocksByDisplay.values.sorted { $0.displayID < $1.displayID },
            manualProtections: settings.manualProtections.sorted { $0.displayID < $1.displayID },
            pendingPreflight: pendingPreflight,
            lastIssue: persistenceIssue ?? loadIssue
        )
        // An older publish may have awaited several actors while a newer state
        // was already published. Never let the older result overwrite it.
        guard generation == publishGeneration else { return }
        snapshot = next
        onSnapshotChange?(next)
    }

    // MARK: Event helpers

    private static func desktopEvent(for event: MacSystemEvent) -> DesktopEvent {
        switch event {
        case .activeSpaceDidChange:
            return .spaceDidChange
        case .screenParametersChanged:
            return .displayConfigurationChanged
        case .screensDidWake, .systemDidWake:
            return .systemWake
        case .sessionDidBecomeActive:
            return .userLogin
        }
    }

    private static func eventName(_ event: MacSystemEvent) -> String {
        switch event {
        case .activeSpaceDidChange:
            return "activeSpaceDidChange"
        case .screenParametersChanged:
            return "screenParametersChanged"
        case .screensDidWake:
            return "screensDidWake"
        case .systemDidWake:
            return "systemDidWake"
        case .sessionDidBecomeActive:
            return "sessionDidBecomeActive"
        }
    }

    private static func merged(
        _ existing: MacSystemEvent?,
        _ new: MacSystemEvent
    ) -> MacSystemEvent {
        guard let existing else { return new }
        return priority(of: new) >= priority(of: existing) ? new : existing
    }

    private static func priority(of event: MacSystemEvent) -> Int {
        switch event {
        case .sessionDidBecomeActive:
            return 5
        case .systemDidWake, .screensDidWake:
            return 4
        case .screenParametersChanged:
            return 3
        case .activeSpaceDidChange:
            return 2
        }
    }
}
